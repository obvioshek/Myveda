/** The walk in Hindi: each step with its pair, the passage's original and reference from the English data. */
export function hiWalk() {
  return WALK.map((w, i) => {
    const en = pairView(w);
    const hi = HI_WALK[i];
    // The English quote opens with its translation in quotes; keep the original and reference.
    const rest = en.quote.replace(/^“[^”]*”\s*/, "");
    return { ...hi, kind: en.kind, quoteHtml: `“${hi.quote}” ${rest}`, href: passageHref(w.slug, w.pairing), chapter: en.chapter, concept: en.concept };
  });
}

export function hiWords() {
  return WORDS.map(w => ({ id: w.id, term: w.term, original: w.original, lang: w.lang, ...HI_WORDS[w.id] }));
}

/** Unit 1's glossary in Hindi, in the Hindi alphabetical order of the terms. */
export function hiGlossary() {
  return GLOSSARY.filter(t => HI_UNIT1[t.id]).map(t => {
    const [hiTerm, hiDef] = HI_UNIT1[t.id];
    const c = chapterBySlug(t.chapterSlug)!;
    return { id: t.id, en: t.term, term: hiTerm, def: hiDef, chapter: c.short ?? c.title, href: `/learn/${c.slug}` };
  }).sort((a, b) => a.term.localeCompare(b.term, "hi"));
}

// Checked when the site is built: every step, word and Unit 1 term has its Hindi.
{
  const bad: string[] = [];
  if (HI_WALK.length !== WALK.length) bad.push(`the walk has ${WALK.length} steps but ${HI_WALK.length} in Hindi`);
  for (const w of WORDS) if (!HI_WORDS[w.id]) bad.push(`no Hindi for the word "${w.id}"`);
  for (const t of GLOSSARY.filter(t => t.unitN === 1)) if (!HI_UNIT1[t.id]) bad.push(`no Hindi for Unit 1 term "${t.id}"`);
  for (const id of Object.keys(HI_UNIT1)) if (!GLOSSARY.some(t => t.id === id)) bad.push(`Hindi term "${id}" is not in the glossary`);
  if (bad.length) throw new Error(`content/hi:\n- ${bad.join("\n- ")}`);
}
